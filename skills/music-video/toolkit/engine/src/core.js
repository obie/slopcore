// core.js: the stage, SCENE registration, ENGINE.render(t) and the purity guards.
'use strict';

// The stage is 1920 x 1080. `?size=WxH` (render.py --size 1080x1920) makes it another size, for a vertical
// cut; W and H follow, and with them everything that lays out by W and H. Without it nothing changes.
const [W, H] = (() => {
  const s = new URLSearchParams(location.search).get('size');
  if (!s) return [1920, 1080];
  const m = /^(\d+)x(\d+)$/.exec(s);
  if (!m || m[1] % 2 || m[2] % 2 || m[1] < 2 || m[2] < 2) throw new Error(`size must be WxH in even pixels, e.g. 1080x1920, got "${s}"`);
  return [Number(m[1]), Number(m[2])];
})();

// Filled by <project>/engine/assets/*.js (generated by `render.py assets`).
const ASSETS = { beats: null, lyrics: null, plates: {}, clips: {}, chapters: [] };

// Every canvas the engine or a chapter creates goes through CANVAS.make, so all of them are CPU canvases
// (willReadFrequently). A canvas that starts on the GPU and moves to the CPU after a readback rasterises
// differently before and after, which makes a frame depend on what was rendered earlier.
const CANVAS = {
  make(w = W, h = H) {
    const c = document.createElement('canvas');
    c.width = w; c.height = h;
    c.ctx = c.getContext('2d', { willReadFrequently: true });
    return c;
  },
  _pool: new Map(),
  // scratch(key) -> a cleared, state-reset 2D context of a pooled offscreen canvas. Cleared on every call.
  scratch(key = 0, w = W, h = H) {
    let c = this._pool.get(key);
    if (!c) this._pool.set(key, (c = this.make(w, h)));
    if (c.width !== w || c.height !== h) { c.width = w; c.height = h; }
    c.ctx.reset();
    return c.ctx;
  },
};

const _stage = document.getElementById('stage');
if (_stage.width !== W || _stage.height !== H) { _stage.width = W; _stage.height = H; }
const _ctx = _stage.getContext('2d', { willReadFrequently: true });
_stage.ctx = _ctx;

// save/restore are counted so a scene that leaks state fails instead of bleeding into the next scene.
let _depth = 0, _floor = 0, _drawing = false;
const _save = _ctx.save.bind(_ctx), _restore = _ctx.restore.bind(_ctx), _reset = _ctx.reset.bind(_ctx);
_ctx.save = () => { _depth++; _save(); };
_ctx.restore = () => {
  if (_depth <= _floor) throw new Error('ctx.restore() without a matching ctx.save()');
  _depth--; _restore();
};
_ctx.reset = () => {
  if (_drawing) throw new Error('ctx.reset() on the frame context is not allowed inside draw()');
  _depth = 0; _reset();
};

// While a frame draws, the clocks and Math.random throw.
const _RealDate = Date, _random = Math.random;
const _impure = what => () => {
  throw new Error(`PURITY: ${what} called while a frame renders. A frame is a pure function of t: use hash(n) or rnd(seed).`);
};
class _GuardDate extends _RealDate {
  constructor(...a) { if (!a.length) _impure('new Date()')(); super(...a); }
  static now() { return _impure('Date.now()')(); }
}
function _guard(on) {
  _drawing = on;
  if (on) {
    Math.random = _impure('Math.random()');
    performance.now = _impure('performance.now()');
    window.Date = _GuardDate;
  } else {
    Math.random = _random;
    delete performance.now;
    window.Date = _RealDate;
  }
}

const SCENES = [];

// SCENE({id, t0, t1, z, draw(ctx, t, lt)}): draws on every frame with t0 <= t < t1, lt = t - t0, in z order.
// {proof: true} marks a scene that is not part of the video (a timing proof, a test card): it registers only
// when its chapter was picked with ?ch= / --ch, so it can never satisfy the lyric gate for the real chapters.
function SCENE(def) {
  const { id, t0, t1, draw } = def || {};
  if (def && def.proof && !ENGINE.picked.length) { ENGINE.skipped.push(id); return null; }
  if (typeof id !== 'string' || !id) throw new Error('SCENE: id must be a non-empty string');
  if (SCENES.some(s => s.id === id)) throw new Error(`SCENE: duplicate id "${id}"`);
  if (!(Number.isFinite(t0) && Number.isFinite(t1) && t0 < t1)) throw new Error(`SCENE "${id}": need finite t0 < t1, got ${t0}, ${t1}`);
  if (typeof draw !== 'function') throw new Error(`SCENE "${id}": draw must be a function`);
  const s = Object.freeze({ id, t0, t1, z: Number(def.z) || 0, draw, order: SCENES.length, file: ENGINE._file });
  SCENES.push(s);
  return s;
}

const ENGINE = {
  W, H,
  canvas: _stage,
  ctx: _ctx,
  scenes: SCENES,
  project: null,
  look: 'native',     // mode handed to look(ctx, mode) after the last scene
  marks: [],          // LY.mark() records of the last rendered frame: [{li, wi, px}]
  t: null,            // time of the last rendered frame
  ready: null,        // set by boot.js; resolves when assets, fonts and chapters are loaded
  picked: [],         // chapter prefixes from ?ch=, empty when every chapter is loaded
  skipped: [],        // ids of proof scenes left out because no chapter was picked
  _file: null,
  _busy: false,

  // scenes drawn at time t, in draw order
  active(t) {
    return SCENES.filter(s => s.t0 <= t && t < s.t1).sort((a, b) => a.z - b.z || a.order - b.order);
  },

  // Draw the frame for song time t. Resolves when every image the frame asked for is decoded and drawn.
  async render(t) {
    if (!Number.isFinite(t)) throw new Error(`ENGINE.render: bad time ${t}`);
    if (this._busy) throw new Error('ENGINE.render: a render is already in flight');
    this._busy = true;
    try {
      await this.ready;
      MEDIA._evict();
      for (let pass = 1; pass <= 8; pass++) {
        MEDIA._pending.length = 0;
        const ids = this._draw(t);
        if (!MEDIA._pending.length) {
          _ctx.getImageData(0, 0, 1, 1);   // canvas draws are recorded lazily; a readback rasterises the frame now
          this.t = t;
          return { t, scenes: ids, passes: pass, marks: this.marks.length };
        }
        await Promise.all(MEDIA._pending);
      }
      throw new Error(`ENGINE.render: t=${t} still waiting on media after 8 passes`);
    } finally {
      this._busy = false;
    }
  },

  // One synchronous draw pass. Media that is not decoded yet is skipped and queued; render() repeats the pass.
  _draw(t) {
    const ctx = _ctx;
    _floor = 0; _depth = 0; _reset();
    ctx.fillStyle = '#000';
    ctx.fillRect(0, 0, W, H);
    this.marks = [];
    const act = this.active(t);
    _guard(true);
    try {
      for (const s of act) {
        ctx.save(); _floor = _depth;
        try {
          s.draw(ctx, t, t - s.t0);
        } catch (e) {
          throw new Error(`scene "${s.id}" at t=${t}: ${e.message}\n${e.stack || ''}`);
        }
        if (_depth !== _floor) throw new Error(`scene "${s.id}" at t=${t}: ${_depth - _floor} ctx.save() without ctx.restore()`);
        _floor = 0; ctx.restore();
      }
      ctx.save(); _floor = _depth;
      look(ctx, this.look);
      if (_depth !== _floor) throw new Error(`look "${this.look}": unbalanced ctx.save()`);
      _floor = 0; ctx.restore();
    } finally {
      _guard(false); _floor = 0;
    }
    return act.map(s => s.id);
  },
};
