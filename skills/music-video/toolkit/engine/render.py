#!/usr/bin/env python3
"""render.py <cmd>: render the motion-design engine in headless Chromium (stills, sheets, frames, video, checks).

Run from engine/ with the project directory (relative to the repo root) in VIDEO_PROJECT:

    cd engine && VIDEO_PROJECT=<project> python3 render.py <cmd>

    assets                                   regenerate <project>/engine/assets/ (beats.js, lyrics.js, plates.js,
                                             clips.js, chapters.js) from media/audio/*.json and the media and ch/
                                             folders. Every other command does this first. A project with
                                             shots.json or edl.json at its root also gets shots.js (window.SHOTS)
                                             and edl.js (window.EDL).
    still <t> --out f.png                    one frame at song time t (seconds)
    sheet <t1,t2,..|A:B:n> --cols 4 --w 480 --out f.jpg
                                             contact sheet, each tile captioned with its time. A:B:n is n times
                                             A + k*(B-A)/n, k = 0..n-1.
    frames A:B --fps 24 --out dir --workers N    numbered frames dir/f00001.png ... (--fmt jpg for JPEG)
    video A:B --out f.mp4 --fps 24 --workers N [--w 1920] [--no-audio]
                                             H.264 CRF 16, yuv420p, BT.709, AAC 256k from media/audio/song.wav at A
    lyrics [A:B] [--workers N]               THE GATE: every sung word whose midpoint is in range is rendered at
                                             that midpoint and must carry an LY.mark at 36 px or taller. Prints
                                             N/N and every miss with its time; exits 1 on any miss.
    check [A:B] --n 24                       purity: n frames in order, then the same times shuffled in a fresh
                                             browser; pixel hashes must match. Prints HISTORY-INDEPENDENT or the
                                             failing times; exits 1 on a mismatch.
    bench [A:B]                              ms per frame: render alone, each frame transfer method, the video pipe

Every command takes --ch 03,07 (load only chapters whose file name starts with one of the prefixes) and
--look <mode>. Scenes registered with proof: true, such as the timing proof in ch/00_timing.js, load only
when their chapter is picked with --ch.

Frame i of a range is song time A + i/fps. A:B covers ceil((B-A)*fps) frames. The range is split into chunks
of 8 s that N cold browsers pull from a queue. `video` encodes one segment per chunk and joins the segments
without re-encoding.

Frame transfer, chosen from `bench` on the M2 Ultra: getImageData on the CPU canvas (2 ms), the bytes wrapped
in a Blob and POSTed to this script's HTTP server (10 ms), then written to ffmpeg's stdin as rawvideo. It is
lossless and costs the same 12 ms for any picture. The same bytes sent as a typed array take 230 to 530 ms,
base64 over CDP 350 ms, page.screenshot 45 to 150 ms. PNG toBlob is 10 to 15 ms on flat graphics and slower
than raw on photographs. Loopback tops out near 250 frames per second across all workers, and more than 8
workers is slower.
"""
import argparse, asyncio, http.server, json, math, os, pathlib, random, shutil, subprocess, sys, threading, time
import urllib.parse

HERE = pathlib.Path(__file__).resolve().parent
ROOT = HERE.parent
PROJECT = os.environ.get('VIDEO_PROJECT', '').strip('/')
P = ROOT / PROJECT
W, H = 1920, 1080
MIN_PX = 36
CHUNK_S = 8.0   # seconds of song per work chunk
BATCH = 12       # frames rendered per call into the page
CHROME_ARGS = ['--disable-accelerated-2d-canvas', '--force-color-profile=srgb', '--disable-background-timer-throttling',
               '--disable-renderer-backgrounding', '--disable-backgrounding-occluded-windows']


# ---------------------------------------------------------------- assets

def gen_assets(verbose=False):
    """Write <project>/engine/assets/*.js. Files are replaced atomically and only when their content changes."""
    out = P / 'engine/assets'
    out.mkdir(parents=True, exist_ok=True)
    head = '// generated by engine/render.py assets. Do not edit.\n'
    js = lambda o: json.dumps(o, ensure_ascii=False, separators=(',', ':'))
    changed = []

    def put(name, body):
        f, text = out / name, head + body
        if f.exists() and f.read_text() == text: return
        tmp = out / f'.{name}.{os.getpid()}.tmp'
        tmp.write_text(text); os.replace(tmp, f); changed.append(name)

    beat = json.loads((P / 'media/audio/beatmap.json').read_text())
    put('beats.js', 'ASSETS.beats = ' + js({k: beat[k] for k in ('duration', 'bpm', 'period', 't0')}) + ';\n')

    words = json.loads((P / 'media/audio/words.json').read_text())
    rows = [js({'li': L['li'], 'section': L['section'], 'stanza': L['stanza'], 'text': L['text'], 'aside': bool(L['aside']),
                't0': L['t0'], 't1': L['t1'], 'words': [{'w': w['w'], 't0': w['t0'], 't1': w['t1']} for w in L['words']]})
            for L in words['lines']]
    put('lyrics.js', 'ASSETS.lyrics = {duration:' + js(words['duration']) + ',lines:[\n' + ',\n'.join(rows) + '\n]};\n')

    plates = {}
    for f in sorted((P / 'media/plates').glob('*.jpg')):
        plates[f.stem] = {'matte': (f.parent / f'{f.stem}.matte.png').exists()}
    put('plates.js', 'ASSETS.plates = ' + js(plates) + ';\n')

    clips = {}
    cdir = P / 'media/clipframes'
    for d in sorted(x for x in cdir.iterdir() if x.is_dir()) if cdir.is_dir() else []:
        names = sorted(f.name for f in d.glob('f[0-9]*.jpg'))
        want = [f'f{i + 1:05d}.jpg' for i in range(len(names))]
        if not names or names != want:
            print(f'assets: skipping clip {d.name}: frames must be f00001.jpg .. with no gaps ({len(names)} found)', file=sys.stderr)
            continue
        mattes = sorted(f.name for f in (d / 'matte').glob('f[0-9]*.png'))
        matte = mattes == [n[:-4] + '.png' for n in names]
        if mattes and not matte:
            print(f'assets: clip {d.name}: matte/ has {len(mattes)} frames for {len(names)} clip frames; matte ignored', file=sys.stderr)
        clips[d.name] = {'n': len(names), 'fps': 24, 'matte': matte}
    put('clips.js', 'ASSETS.clips = ' + js(clips) + ';\n')

    chapters = sorted(f.name for f in (P / 'engine/ch').glob('*.js'))
    put('chapters.js', 'ASSETS.chapters = ' + js(chapters) + ';\n')

    # Optional project data: <project>/shots.json -> assets/shots.js (window.SHOTS), <project>/edl.json ->
    # assets/edl.js (window.EDL). boot.js does not load these two files; a project that wants them loads them
    # from its common.js. A project without the JSON files gets no extra asset files.
    for name, var in (('shots', 'SHOTS'), ('edl', 'EDL')):
        src = P / f'{name}.json'
        if src.exists(): put(f'{name}.js', f'window.{var} = ' + js(json.loads(src.read_text())) + ';\n')

    if verbose:
        n_words = sum(len(L['words']) for L in words['lines'])
        print(f'{out.relative_to(ROOT)}: beats (period {beat["period"]} s, t0 {beat["t0"]} s), {len(rows)} lines / {n_words} words, '
              f'{len(plates)} plates ({sum(p["matte"] for p in plates.values())} matted), '
              f'{len(clips)} clips ({sum(c["matte"] for c in clips.values())} matted), {len(chapters)} chapters: {", ".join(chapters)}')
        print('rewrote: ' + (', '.join(changed) if changed else 'nothing (up to date)'))
    return {'duration': beat['duration'], 'lines': words['lines'], 'chapters': chapters}


# ---------------------------------------------------------------- local server

SINKS = {}   # POST path -> callable(bytes)

class Handler(http.server.SimpleHTTPRequestHandler):
    """Serves engine/ and <project>/{engine,media}/ from the repo root; takes frame POSTs on /__sink/<id>."""
    protocol_version = 'HTTP/1.1'

    def __init__(self, *a, **k):
        super().__init__(*a, directory=str(ROOT), **k)

    def log_message(self, *a):
        pass

    def end_headers(self):
        self.send_header('Cache-Control', 'no-store')
        super().end_headers()

    def _empty(self, code, msg=b''):
        self.send_response(code)
        self.send_header('Content-Length', str(len(msg)))
        self.end_headers()
        self.wfile.write(msg)

    def do_GET(self):
        path = urllib.parse.unquote(urllib.parse.urlsplit(self.path).path)
        parts = [p for p in path.split('/') if p]
        ok = (path.startswith('/engine/') or path.startswith(f'/{PROJECT}/engine/') or path.startswith(f'/{PROJECT}/media/'))
        if path == '/favicon.ico': return self._empty(204)
        if not ok or any(p.startswith('.') for p in parts): return self._empty(403)
        super().do_GET()

    def do_POST(self):
        n = int(self.headers.get('Content-Length') or 0)
        buf = bytearray(n)
        view, got = memoryview(buf), 0
        while got < n:
            r = self.rfile.readinto(view[got:])
            if not r: break
            got += r
        fn = SINKS.get(self.path)
        try:
            if fn is None: raise KeyError(f'no sink at {self.path}')
            if got < n: raise IOError(f'short body {got}/{n}')
            fn(buf)
            self._empty(200)
        except Exception as e:
            self._empty(500, repr(e).encode())

class Server(http.server.ThreadingHTTPServer):
    daemon_threads = True
    request_queue_size = 1024   # N browsers open six connections each at once; the default backlog of 5 drops some

def serve():
    srv = Server(('127.0.0.1', 0), Handler)
    threading.Thread(target=srv.serve_forever, daemon=True).start()
    return srv.server_address[1]


# ---------------------------------------------------------------- pages

class Pg:
    """One cold headless Chromium with the engine page loaded and its own POST sink."""
    count = 0

    @classmethod
    async def open(cls, pw, url):
        self = cls()
        Pg.count += 1
        self.sink_path, self.sink, self.errors = f'/__sink/{Pg.count}', None, []
        SINKS[self.sink_path] = lambda b: self.sink(b)
        self.browser = await pw.chromium.launch(headless=True, args=CHROME_ARGS)
        ctx = await self.browser.new_context(viewport={'width': W, 'height': H}, device_scale_factor=1)
        self.page = await ctx.new_page()
        self.page.on('pageerror', lambda e: self.errors.append(str(e)))
        self.page.on('console', lambda m: self.errors.append(m.text) if m.type == 'error' else None)
        await self.page.goto(url)
        try:
            self.info = await self.page.evaluate('ENGINE.ready')
        except Exception as e:
            raise SystemExit('engine failed to load:\n' + clean(e) + ''.join(f'\n  {x}' for x in self.errors))
        if Pg.count == 1:
            if self.info['skipped']:
                print(f'note: proof scene(s) {", ".join(self.info["skipped"])} not loaded; pick their chapter with --ch to draw them', file=sys.stderr)
            if not self.info['scenes']: print('note: no scenes registered', file=sys.stderr)
        return self

    async def ev(self, expr, *args):
        return await self.page.evaluate(expr, list(args))

    async def close(self):
        SINKS.pop(self.sink_path, None)
        await self.browser.close()

def clean(e):
    return str(e).removeprefix('Page.evaluate: ').removeprefix('Error: ')

class Progress:
    def __init__(self, total, what):
        self.total, self.what, self.done, self.t0, self.last = total, what, 0, time.time(), time.time()
    def tick(self, n=1):
        self.done += n
        now = time.time()
        if now - self.last >= 5 and self.done < self.total:
            self.last, rate = now, self.done / (now - self.t0)
            print(f'  {self.what} {self.done}/{self.total}  {rate:.1f}/s  eta {(self.total - self.done) / rate:.0f}s', flush=True)

async def pool(pw, url, chunks, workers, job, prefetch=0):
    """Run job(pg, chunk) for every chunk on up to `workers` cold pages. Returns results in chunk order."""
    q = asyncio.Queue()
    for i, c in enumerate(chunks): q.put_nowait((i, c))
    res = [None] * len(chunks)
    pages = [await Pg.open(pw, url)]
    pages += await asyncio.gather(*[Pg.open(pw, url) for _ in range(max(1, min(workers, len(chunks))) - 1)])
    async def run(pg):
        if prefetch: await pg.page.evaluate(f'MEDIA.prefetch = {int(prefetch)}')
        while True:
            try: i, c = q.get_nowait()
            except asyncio.QueueEmpty: return
            res[i] = await job(pg, c)
    tasks = [asyncio.ensure_future(run(pg)) for pg in pages]
    try:
        done, pending = await asyncio.wait(tasks, return_when=asyncio.FIRST_EXCEPTION)
        for t in pending: t.cancel()
        await asyncio.gather(*pending, return_exceptions=True)
        for t in done: t.result()
    finally:
        await asyncio.gather(*[pg.close() for pg in pages], return_exceptions=True)
    return res


# ---------------------------------------------------------------- times

def span(s, dur):
    if not s: return 0.0, float(dur)
    a, b = s.split(':')
    a, b = float(a), float(b)
    if not b > a: raise SystemExit(f'bad range {s}: need A:B with B > A (seconds)')
    return a, b

def frame_times(a, b, fps):
    return [a + i / fps for i in range(math.ceil((b - a) * fps - 1e-6))]

def chunked(items, size):
    return [items[i:i + size] for i in range(0, len(items), size)]

def chunk_size(n, fps, workers):
    return max(1, min(round(CHUNK_S * fps), math.ceil(n / max(1, workers))))


# ---------------------------------------------------------------- ffmpeg

def x264_from_raw(path, fps, w=W):
    """ffmpeg reading raw RGBA frames on stdin, writing H.264 CRF 16 yuv420p tagged BT.709."""
    vf = (f'scale={w}:-2:flags=lanczos+accurate_rnd+full_chroma_int:in_range=pc:out_range=tv:out_color_matrix=bt709,'
          'format=yuv420p,setparams=range=tv:colorspace=bt709:color_primaries=bt709:color_trc=bt709')
    cmd = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-f', 'rawvideo', '-pix_fmt', 'rgba', '-s', f'{W}x{H}',
           '-r', f'{fps:g}', '-i', '-', '-vf', vf, '-c:v', 'libx264', '-crf', '16', '-preset', 'medium', '-pix_fmt', 'yuv420p',
           '-colorspace', 'bt709', '-color_primaries', 'bt709', '-color_trc', 'bt709', '-color_range', 'tv', str(path)]
    return subprocess.Popen(cmd, stdin=subprocess.PIPE)

def probe(path):
    r = subprocess.run(['ffprobe', '-v', 'error', '-count_packets', '-show_entries',
                        'format=duration:stream=codec_type,codec_name,nb_read_packets,width,height,pix_fmt,color_space,color_transfer,color_primaries,color_range,duration',
                        '-of', 'json', str(path)], capture_output=True, text=True)
    return json.loads(r.stdout)


# ---------------------------------------------------------------- commands

async def cmd_still(pw, url, a, meta):
    out = pathlib.Path(a.out).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    pg = await Pg.open(pw, url)
    pg.sink = out.write_bytes
    kind = 'jpeg' if out.suffix.lower() in ('.jpg', '.jpeg') else 'png'
    info = await pg.ev('([t, u, k]) => HOST.frame(t, u, k)', a.t, pg.sink_path, kind)
    await pg.close()
    print(f'{out}  t={a.t:g}  scenes: {", ".join(info["scenes"]) or "none"}  passes={info["passes"]}  marks={info["marks"]}')

def sheet_times(spec):
    if ':' in spec:
        a, b, n = spec.split(':')
        a, b, n = float(a), float(b), int(n)
        return [round(a + k * (b - a) / n, 4) for k in range(n)]
    return [float(x) for x in spec.split(',') if x.strip()]

async def cmd_sheet(pw, url, a, meta):
    times = sheet_times(a.times)
    out = pathlib.Path(a.out).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    pg = await Pg.open(pw, url)
    pg.sink = out.write_bytes
    await pg.ev('([n, c, w]) => HOST.sheetBegin(n, c, w)', len(times), a.cols, a.w)
    for i, t in enumerate(times):
        await pg.ev('([i, t, l]) => HOST.sheetTile(i, t, l)', i, t, f'{t:.3f}'.rstrip('0').rstrip('.') + 's')
    kind = 'png' if out.suffix.lower() == '.png' else 'jpeg'
    w, h = await pg.ev('([u, k]) => HOST.sheetEnd(u, k)', pg.sink_path, kind)
    await pg.close()
    print(f'{out}  {len(times)} tiles, {a.cols} columns, {w}x{h}')

async def cmd_frames(pw, url, a, meta):
    A, B = span(a.range, meta['duration'])
    times = list(enumerate(frame_times(A, B, a.fps)))
    out = pathlib.Path(a.out).resolve()
    out.mkdir(parents=True, exist_ok=True)
    ext, kind = ('jpg', 'jpeg') if a.fmt == 'jpg' else ('png', 'png')
    prog, t0 = Progress(len(times), 'frames'), time.time()
    async def job(pg, chunk):
        for i, t in chunk:
            pg.sink = (out / f'f{i + 1:05d}.{ext}').write_bytes
            await pg.ev('([t, u, k]) => HOST.frame(t, u, k)', t, pg.sink_path, kind)
            prog.tick()
    await pool(pw, url, chunked(times, chunk_size(len(times), a.fps, a.workers)), a.workers, job, prefetch=2)
    dt = time.time() - t0
    print(f'{out}/f00001.{ext} .. f{len(times):05d}.{ext}  {len(times)} frames in {dt:.1f}s ({len(times) / dt:.1f} fps)')

async def cmd_video(pw, url, a, meta):
    A, B = span(a.range, meta['duration'])
    times = frame_times(A, B, a.fps)
    out = pathlib.Path(a.out).resolve()
    out.parent.mkdir(parents=True, exist_ok=True)
    tmp = P / f'media/scratch/.render-{os.getpid()}'
    tmp.mkdir(parents=True, exist_ok=True)
    chunks = list(enumerate(chunked(times, chunk_size(len(times), a.fps, a.workers))))
    prog, t0 = Progress(len(times), 'frames'), time.time()
    async def job(pg, chunk):
        k, ts = chunk
        seg = tmp / f'seg{k:05d}.mp4'
        proc = x264_from_raw(seg, a.fps, a.w)
        pg.sink = proc.stdin.write
        try:
            for part in chunked(ts, BATCH):
                await pg.ev('([ts, u]) => HOST.frames(ts, u, "raw")', part, pg.sink_path)
                prog.tick(len(part))
        finally:
            proc.stdin.close()
            rc = await asyncio.to_thread(proc.wait)
        if rc: raise RuntimeError(f'ffmpeg failed on segment {k} (exit {rc})')
        return seg
    try:
        segs = await pool(pw, url, chunks, a.workers, job, prefetch=2)
        t_render = time.time() - t0
        (tmp / 'list.txt').write_text(''.join(f"file '{s}'\n" for s in segs))
        song = P / 'media/audio/song.wav'
        audio = not a.no_audio and song.exists()
        if not a.no_audio and not song.exists(): print(f'no {song}; writing video without audio', file=sys.stderr)
        cmd = ['ffmpeg', '-hide_banner', '-loglevel', 'error', '-y', '-f', 'concat', '-safe', '0', '-i', str(tmp / 'list.txt')]
        if audio: cmd += ['-ss', f'{A:.6f}', '-t', f'{len(times) / a.fps:.6f}', '-i', str(song), '-map', '0:v', '-map', '1:a', '-c:a', 'aac', '-b:a', '256k']
        cmd += ['-c:v', 'copy', '-movflags', '+faststart', str(out)]
        subprocess.run(cmd, check=True)
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    info = probe(out)
    v = next(s for s in info['streams'] if s['codec_type'] == 'video')
    au = next((s for s in info['streams'] if s['codec_type'] == 'audio'), None)
    dt = time.time() - t0
    tags = '/'.join(str(v.get(k)) for k in ('color_space', 'color_transfer', 'color_primaries', 'color_range'))
    print(f'{out}  {v["width"]}x{v["height"]} {v["codec_name"]} {v["pix_fmt"]} {tags}  '
          f'{v["nb_read_packets"]} frames (expected {len(times)})  duration {float(info["format"]["duration"]):.3f}s  '
          f'audio: {au["codec_name"] + " " + format(float(au["duration"]), ".3f") + "s" if au else "none"}')
    print(f'rendered {len(times)} frames in {t_render:.1f}s with {min(a.workers, len(chunks))} workers '
          f'({len(times) / t_render:.1f} fps, {1000 * t_render / len(times):.1f} ms/frame wall); total {dt:.1f}s')
    if int(v['nb_read_packets']) != len(times): raise SystemExit('frame count mismatch')

async def cmd_lyrics(pw, url, a, meta):
    A, B = span(a.range, meta['duration'])
    words = []
    for L in meta['lines']:
        for wi, w in enumerate(L['words']):
            mid = (w['t0'] + w['t1']) / 2
            if A <= mid < B: words.append((mid, L['li'], wi, w['w']))
    words.sort()
    if not words: raise SystemExit(f'no sung words with a midpoint in {A:g}:{B:g}')
    prog = Progress(len(words), 'words')
    async def job(pg, chunk):
        miss = []
        for mid, li, wi, w in chunk:
            marks = await pg.ev('([t]) => HOST.marks(t)', mid)
            px = [m['px'] for m in marks if m['li'] == li and m['wi'] == wi]
            if not px: miss.append((mid, li, wi, w, 'no mark'))
            elif max(px) < MIN_PX: miss.append((mid, li, wi, w, f'{max(px):.1f} px, under {MIN_PX}'))
            prog.tick()
        return miss
    res = await pool(pw, url, chunked(words, 16), a.workers, job)
    miss = sorted(m for r in res for m in r)
    for mid, li, wi, w, why in miss:
        print(f'MISS t={mid:8.3f}  line {li:3d} word {wi}  {w!r}: {why}')
    print(f'{len(words) - len(miss)}/{len(words)}')
    if miss: sys.exit(1)

async def cmd_check(pw, url, a, meta):
    A, B = span(a.range, meta['duration'])
    fps = 24
    times = sorted({round((A + (k + 0.5) * (B - A) / a.n) * fps) / fps for k in range(a.n)})
    async def hashes(order):
        pg = await Pg.open(pw, url)
        out = {}
        for t in order: out[t] = await pg.ev('([t]) => HOST.hash(t)', t)
        await pg.close()
        return out
    first = await hashes(times)
    shuffled = times[:]
    random.Random(a.seed).shuffle(shuffled)
    second = await hashes(shuffled)
    bad = [t for t in times if first[t] != second[t]]
    for t in bad: print(f'DIFFERS t={t:.4f}  in order {first[t][:16]}  shuffled {second[t][:16]}')
    print(f'{len(times) - len(bad)}/{len(times)} frames identical between an in-order pass and a shuffled pass in a fresh browser '
          f'({A:g}:{B:g}, {len(set(first.values()))} distinct frames)')
    print('HISTORY-INDEPENDENT' if not bad else 'HISTORY-DEPENDENT at t = ' + ', '.join(f'{t:.4f}' for t in bad))
    if bad: sys.exit(1)

async def cmd_bench(pw, url, a, meta):
    dur = meta['duration']
    if a.range:
        A, B = span(a.range, dur)
        times = frame_times(A, B, 24)[:240]
    else:
        times = [dur * f + i / 24 for f in (1 / 6, 3 / 6, 5 / 6) for i in range(24)]
    n = len(times)
    pg = await Pg.open(pw, url)
    await pg.page.evaluate('MEDIA.prefetch = 2')
    for t in times[:6]: await pg.ev('([t]) => ENGINE.render(t).then(() => 0)', t)   # warm fonts and JIT
    rows = []
    async def run(name, fn, note=''):
        t0 = time.time()
        for t in times: await fn(t)
        ms = 1000 * (time.time() - t0) / n
        rows.append((name, ms, note))
        print(f'  {name:<34}{ms:8.1f} ms/frame   {note}', flush=True)
        return ms
    print(f'{n} frames at 1920x1080, one page, project {PROJECT}')
    base = await run('render only', lambda t: pg.ev('([t]) => ENGINE.render(t).then(() => 0)', t), 'drawn and rasterised, no pixels leave the page')
    pg.sink = lambda b: None
    await run('raw RGBA as Blob, POST', lambda t: pg.ev('([t, u]) => HOST.frame(t, u, "raw").then(() => 0)', t, pg.sink_path), 'lossless')
    await run('raw RGBA as typed array, POST', lambda t: pg.ev('([t, u]) => HOST.frame(t, u, "raw-view").then(() => 0)', t, pg.sink_path), 'lossless')
    await run('PNG toBlob, POST', lambda t: pg.ev('([t, u]) => HOST.frame(t, u, "png").then(() => 0)', t, pg.sink_path), 'lossless')
    await run('JPEG q0.95 toBlob, POST', lambda t: pg.ev('([t, u]) => HOST.frame(t, u, "jpeg").then(() => 0)', t, pg.sink_path), 'lossy')
    b64 = '''([t]) => ENGINE.render(t).then(() => { const d = HOST.raw(); let s = '';
        for (let i = 0; i < d.length; i += 32768) s += String.fromCharCode.apply(null, d.subarray(i, i + 32768)); return btoa(s); })'''
    await run('raw RGBA, base64 over CDP', lambda t: pg.ev(b64, t), 'lossless')
    await run('PNG toDataURL over CDP', lambda t: pg.ev('([t]) => ENGINE.render(t).then(() => ENGINE.canvas.toDataURL("image/png"))', t), 'lossless')
    async def shot(t, **k):
        await pg.ev('([t]) => ENGINE.render(t).then(() => 0)', t)
        await pg.page.screenshot(clip={'x': 0, 'y': 0, 'width': W, 'height': H}, **k)
    await run('page.screenshot PNG', lambda t: shot(t, type='png'), 'lossless, through the compositor')
    await run('page.screenshot JPEG q95', lambda t: shot(t, type='jpeg', quality=95), 'lossy')
    tmp = P / f'media/scratch/.bench-{os.getpid()}'
    tmp.mkdir(parents=True, exist_ok=True)
    try:
        proc = x264_from_raw(tmp / 'bench.mp4', 24)
        pg.sink = proc.stdin.write
        pipe = await run('raw RGBA as Blob, POST, x264 CRF 16', lambda t: pg.ev('([t, u]) => HOST.frame(t, u, "raw").then(() => 0)', t, pg.sink_path), 'the `video` path')
        proc.stdin.close(); proc.wait()
    finally:
        shutil.rmtree(tmp, ignore_errors=True)
    await pg.close()
    best = min((r for r in rows[1:-1] if r[2].startswith('lossless')), key=lambda r: r[1])
    print(f'fastest lossless transfer on these frames: {best[0]} (+{best[1] - base:.1f} ms over render). '
          f'`video` sends raw RGBA as a Blob (+{rows[1][1] - base:.1f} ms, the same for any picture, nothing to decode).')
    print(f'one worker through the video pipe: {pipe:.1f} ms/frame = {1000 / pipe:.1f} fps')

